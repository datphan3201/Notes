            <h2>Đặt mục tiêu và lộ trình</h2>
            <p><strong>Khi nào dùng:</strong> khi bạn có một kết quả muốn đạt trong vài tuần hay vài tháng.</p>
            <h3>Tạo mục tiêu</h3>
            <ol class="guide-steps">
