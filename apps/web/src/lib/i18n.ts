const additions: Record<string, string> = {
    "Restore draft": "Khôi phục bản nháp",
    "A recovered draft is available.": "Có bản nháp chưa lưu cần khôi phục.",
    "Repeating task": "Công việc lặp lại",
    "New repeating task": "Công việc lặp lại mới",
    "Scheduled end": "Kết thúc lịch",
};

export function translate(message: string, locale: string, fallback = message) {
    return locale === "vi"
        ? (vietnamese as Record<string, string>)[message] ||
              additions[message] ||
              fallback
        : message;
}

