            <h3>Một số “cam kết” của hệ thống</h3>
            <ul>
                <li><strong>Lưu trữ không phải xóa.</strong> Lĩnh vực, mục tiêu, cột mốc, công việc và thói quen khi lưu trữ chỉ bị ẩn khỏi danh sách; dữ liệu vẫn còn và khôi phục được trong <em>Cài đặt → Lưu trữ</em>. Riêng ghi chú và đánh giá thì xóa là mất hẳn.</li>
                <li><strong>Không ghi đè âm thầm.</strong> Nếu bạn sửa cùng một mục ở hai nơi (ví dụ hai thẻ trình duyệt), Planner sẽ báo và cho bạn chọn <em>Dùng bản đã lưu</em> hoặc <em>Giữ bản nháp của tôi</em>.</li>
                <li><strong>Hoàn thành là do bạn quyết định.</strong> Planner tính tiến độ giúp bạn nhưng không tự đánh dấu mục tiêu hay cột mốc là xong. Khi hoàn thành một việc còn mục kiểm tra chưa tích, Planner sẽ hỏi lại.</li>
                <li><strong>Ngày giờ theo múi giờ của bạn.</strong> “Hôm nay”, hạn chót và giờ nhắc đều tính theo múi giờ trong tài khoản.</li>
                <li><strong>Riêng tư theo mặc định.</strong> Chỉ người bạn mời mới thấy ghi chú được chia sẻ; ghi chú có mật khẩu không bao giờ xuất hiện trong tìm kiếm, bản xem trước hay câu trả lời của AI.</li>
