            <h3>Thẻ Hằng ngày</h3>
            <ol class="guide-steps">
                <li>Ở đầu trang là <strong>lộ trình của mục tiêu chính</strong>. Bấm mũi tên cạnh tên mục tiêu để chọn mục tiêu khác; lựa chọn này cũng chính là <em>Mục tiêu chính</em> trên trang Mục tiêu.</li>
                <li><strong>Công việc hằng ngày</strong> gồm việc bạn chọn cho hôm nay, việc đến hạn hoặc có lịch hôm nay và việc quá hạn gần đây. Vòng tròn phần trăm cho biết bạn đã xong bao nhiêu.</li>
                <li>Bấm <em>Thêm công việc</em> để chọn một việc có sẵn hoặc gõ tên một việc mới cho hôm nay. Việc này không đổi hạn chót của công việc.</li>
                <li>Bấm vòng tròn trước tên việc để đánh dấu xong; bấm lần nữa để mở lại.</li>
                <li>Ở thẻ <strong>Thói quen</strong> bên phải, tích vào ô để đánh dấu thói quen hôm nay. Ngọn lửa cho biết chuỗi ngày bạn đã giữ đủ mọi thói quen hằng ngày.</li>
            </ol>
