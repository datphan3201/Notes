            <h2>Planner là gì?</h2>
            <p><strong>Planner</strong> là một sổ kế hoạch cá nhân trên web. Nó gom vào một nơi những thứ thường nằm rải rác ở nhiều ứng dụng: mục tiêu dài hạn, công việc hằng ngày, thói quen, ghi chú, lịch và những lần nhìn lại bản thân.</p>
            <p>Ý tưởng chính rất đơn giản: <strong>một mục tiêu lớn chỉ thành hiện thực khi được chia thành những việc nhỏ làm được hôm nay.</strong> Planner giúp bạn:</p>
            <ul>
                <li><strong>Biết hôm nay cần làm gì</strong> – trang Tổng quan liệt kê việc của ngày, thói quen cần giữ và việc quá hạn.</li>
                <li><strong>Thấy đường đi tới mục tiêu</strong> – mỗi mục tiêu có một lộ trình gồm các cột mốc và công việc, kèm phần trăm tiến độ.</li>
                <li><strong>Giữ thói quen</strong> – đánh dấu mỗi ngày, xem chuỗi ngày liên tiếp và đặt ngày nghỉ khi cần.</li>
                <li><strong>Lưu lại ý tưởng</strong> – ghi chú có màu, nhãn, danh sách đánh dấu, tệp đính kèm, mật khẩu và chia sẻ.</li>
                <li><strong>Nhìn lại và điều chỉnh</strong> – mỗi ngày, tuần hoặc tháng, Planner tổng hợp những gì bạn đã làm để bạn ghi lại điều tốt, điều chưa tốt và điều sẽ thay đổi.</li>
                <li><strong>Làm cùng người khác</strong> – mục tiêu nhóm có phân công, tiến độ và trò chuyện.</li>
                <li><strong>Nhờ trợ lý AI</strong> – hỏi về kế hoạch, nhờ lập lộ trình hoặc dời lịch; mọi thay đổi chỉ xảy ra khi bạn bấm xác nhận.</li>
            </ul>
