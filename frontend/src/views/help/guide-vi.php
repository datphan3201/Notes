            <h2>Bắt đầu trong 5 phút</h2>
            <ol class="guide-steps">
                <li><strong>Tạo tài khoản.</strong> Ở trang đăng nhập, chọn <em>Tạo tài khoản</em>, nhập tên, email và mật khẩu (ít nhất 10 ký tự). Planner gửi một email xác minh; mở liên kết trong email để kích hoạt. Nếu không thấy email, bấm <em>Gửi lại email</em> trên dải thông báo ở đầu trang.</li>
                <li><strong>Chọn ngôn ngữ và giao diện.</strong> Vào <em>Cài đặt → Giao diện</em> để đổi tiếng Việt/tiếng Anh, chế độ sáng/tối và phong cảnh nền.</li>
                <li><strong>Tạo mục tiêu đầu tiên.</strong> Vào <em>Mục tiêu</em>, bấm <em>Mục tiêu mới</em>, đặt tên (ví dụ “Đạt IELTS 7.0”), chọn lĩnh vực và hạn chót.</li>
                <li><strong>Chia mục tiêu thành cột mốc và công việc.</strong> Mở mục tiêu, bấm <em>Thêm cột mốc</em>, rồi thêm công việc vào từng cột mốc. Nếu muốn nhanh hơn, hãy nhờ trợ lý AI “lập lộ trình” cho bạn.</li>
                <li><strong>Lên kế hoạch cho hôm nay.</strong> Ở <em>Tổng quan</em>, bấm <em>Thêm công việc</em> để chọn việc làm hôm nay. Làm xong, bấm vào vòng tròn trước tên việc để đánh dấu hoàn thành.</li>
            </ol>
